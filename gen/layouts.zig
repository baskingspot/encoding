//! The layouts a multi-byte index can be generated in. Each emits a Zig
//! file with the same public functions, so swapping a table's layout is a
//! one-word change in gen/sources.zig and `just gen`, and no codec
//! changes:
//!
//!     pub fn decode(pointer: u32) u32    // the index code point, or 0
//!     pub fn encode(cp: u21) ?u16        // the index pointer, or null
//!     pub const exclude: []const [2]u32  // the source's encode options,
//!     pub const last: []const u21        // for the full-index check
//!
//! `decode` returns 0 for none rather than an optional, which a caller's
//! loop would carry through memory on every character.
//!
//! Each layout is a file under gen/layouts/ with
//!
//!     pub fn emit(w: *std.Io.Writer, gpa: std.mem.Allocator, src: MultiByte,
//!         entries: []const index.Entry) !void
//!
//! and one line in `impls`. `flat` is the baseline, and the other two are
//! the ones plan decisions 1 and 2 settled on; the rows, ranged, and hash
//! layouts measured against them are written up in
//! docs/slop/results/japanese-tables-20261102.md and
//! chinese-layouts-20261102.md. `zig build test-layouts` checks every
//! layout on every index.

const std = @import("std");
const index = @import("index.zig");
const MultiByte = @import("sources.zig").MultiByte;

/// Every layout, one line each.
const impls = .{
    // The decode table an array indexed by pointer; the encode table the
    // code points sorted with their pointers, searched by bisection.
    .flat = @import("layouts/flat.zig"), // ziglint-ignore: Z028

    // Wave 1, Japanese: decode in pages, encode by rank.
    .japanese_paged = @import("layouts/japanese_paged.zig"), // ziglint-ignore: Z028

    // Wave 1, Chinese: decode flat with a plane-2 bit, encode by rank.
    .chinese_rank = @import("layouts/chinese_rank.zig"), // ziglint-ignore: Z028

    // Wave 2: chinese_rank with runs in the encode table.
    .flat_runs = @import("layouts/flat_runs.zig"), // ziglint-ignore: Z028
};

pub const Layout = std.meta.FieldEnum(@TypeOf(impls));

pub fn emit(
    layout: Layout,
    w: *std.Io.Writer,
    gpa: std.mem.Allocator,
    src: MultiByte,
    entries: []const index.Entry,
) !void {
    try w.print(
        \\//! Generated by `just gen` (gen/main.zig) from vendor/{s}, in the
        \\//! {t} layout (gen/layouts.zig). Do not edit.
        \\
        \\
    , .{ src.file, layout });
    try w.writeAll("pub const exclude: []const [2]u32 = &.{");
    for (src.exclude) |r| try w.print(" .{{ {d}, {d} }},", .{ r[0], r[1] });
    try w.writeAll(" };\npub const last: []const u21 = &.{");
    for (src.last) |cp| try w.print(" 0x{X},", .{cp});
    try w.writeAll(" };\n\n");
    switch (layout) {
        inline else => |t| try @field(impls, @tagName(t)).emit(w, gpa, src, entries),
    }
}

/// The pointer `encode` gives `cp` in the standard: its first pointer in
/// the index outside `exclude`, or its last one when `cp` is in `last`.
pub fn indexPointer(src: MultiByte, entries: []const index.Entry, cp: u21) ?u32 {
    const want_last = std.mem.findScalar(u21, src.last, cp) != null;
    var found: ?u32 = null;
    for (entries) |e| {
        if (e.cp != cp or excluded(src, e.pointer)) continue;
        found = e.pointer;
        if (!want_last) break;
    }
    return found;
}

fn excluded(src: MultiByte, pointer: u32) bool {
    for (src.exclude) |r| {
        if (pointer >= r[0] and pointer <= r[1]) return true;
    }
    return false;
}

pub const Pair = struct { cp: u21, pointer: u32 };

/// The encode table: each code point once, with its index pointer, sorted
/// by code point.
pub fn encodePairs(gpa: std.mem.Allocator, src: MultiByte, entries: []const index.Entry) ![]Pair {
    var map: std.array_hash_map.Auto(u21, u32) = .empty;
    defer map.deinit(gpa);
    for (entries) |e| {
        if (excluded(src, e.pointer)) continue;
        const gop = try map.getOrPut(gpa, e.cp);
        const want_last = std.mem.findScalar(u21, src.last, e.cp) != null;
        if (!gop.found_existing or want_last) gop.value_ptr.* = e.pointer;
    }
    const pairs = try gpa.alloc(Pair, map.count());
    for (map.keys(), map.values(), pairs) |cp, p, *out| out.* = .{ .cp = cp, .pointer = p };
    std.mem.sort(Pair, pairs, {}, struct {
        fn lt(_: void, a: Pair, b: Pair) bool {
            return a.cp < b.cp;
        }
    }.lt);
    return pairs;
}

/// Writes `values` as hex literals, a dozen to a line.
pub fn writeHex(w: *std.Io.Writer, comptime T: type, values: []const T) !void {
    for (values, 0..) |v, i| {
        if (i % 12 == 0) try w.writeAll("   ");
        try w.print(" 0x{X:0>4},", .{v});
        if (i % 12 == 11 or i == values.len - 1) try w.writeAll("\n");
    }
}
